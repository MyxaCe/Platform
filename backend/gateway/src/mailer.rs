//! Отправка писем.
//!
//! Пока почтовый сервер не поднят, письма **не отправляются** — код печатается в лог
//! шлюза, чтобы поток входа можно было проходить целиком. Это честный режим
//! разработки: наружу отдаётся признак `delivered=false`, и интерфейс прямо
//! показывает, что письмо не ушло, а не делает вид, что оно в пути.
//!
//! Когда появится SMTP: задать `SMTP_URL` (и `MAIL_FROM`) — здесь останется одна
//! реализация отправки, вызовы менять не придётся.

/// Настроен ли настоящий отправитель.
pub fn is_configured() -> bool {
    std::env::var("SMTP_URL").map(|v| !v.is_empty()).unwrap_or(false)
}

/// Отправить код подтверждения.
pub async fn send_code(email: &str, code: &str) {
    if is_configured() {
        // TODO(ADR-019): реальная отправка через SMTP, когда поднимем почтовый сервер.
        // Специально не пишем заглушку, которая «как бы отправила»: молчаливая
        // потеря письма хуже явного отказа.
        eprintln!("[mail] SMTP_URL задан, но отправка ещё не реализована — код для {email} не ушёл");
        return;
    }
    println!("[mail] (SMTP не настроен) код подтверждения для {email}: {code}");
}
