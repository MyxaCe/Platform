'use strict';
/* ============================================================================
 * diag.js — общий помощник диагностики отказов канала (TRM-17, ADR-015).
 *
 * ЗАЧЕМ. Политик вывода у нас было изобретено три разными заходами: «на смене
 * состояния» в полосе статистики и в стакане, «первое и каждое пятидесятое» в
 * разборе сообщений фида, счётчик в подсказке индикатора. Каждая защитима для
 * своей частоты — и именно поэтому читатель консоли не знает, какую видит.
 *
 * Политика по умолчанию здесь одна: **писать на смене состояния, считать
 * повторы, называть число при восстановлении**. Отличающуюся политику
 * разрешено **задать** параметром; написать её молча заново — нет.
 *
 * ГРАНИЦА. Это внутренний помощник терминала, а не контракт между
 * репозиториями. Общей диагностики платформы сегодня нет вовсе, и этот файл
 * ею не притворяется. Общее здесь одно — **словарь причин**, и он взят из
 * `КОНТРАКТЫ.md` §4г, а не придуман тут.
 * ========================================================================== */
(function () {
  /**
   * Ось канала (КОНТРАКТЫ §4г): почему потребитель вообще не получил ответа.
   * Имена одинаковы для любого соседа и для любого потребителя платформы.
   *
   * Ось символа (`no-source`, `stale`, `source-disabled`, …) сюда НЕ входит:
   * это другой вопрос — почему нет цены у конкретного инструмента, — и
   * называет её MDS в своём ответе. Сводить две оси в один словарь нельзя,
   * иначе «нет связи» и «источник выключен» окажутся одним словом.
   */
  const CHANNEL = {
    'not-configured': { badge: 'НЕ НАСТРОЕНО', why: 'адрес источника не задан' },
    network: { badge: 'НЕТ СВЯЗИ', why: 'источник не ответил' },
    'http-error': { badge: 'ОТКАЗ ИСТОЧНИКА', why: 'источник ответил отказом' },
    malformed: { badge: 'ОТВЕТ НЕ ТОТ', why: 'источник ответил не тем' },
    empty: { badge: 'ПУСТО', why: 'источник ответил пустым' },
  };

  /**
   * Неизвестное слово — **ошибка, а не пропуск**.
   *
   * Молчаливый пропуск и есть тот способ, которым два словаря расходятся
   * годами: один пишет `unreachable`, другой `network`, фильтр глотает оба, и
   * половина отказов перестаёт находиться поиском. Поэтому здесь бросаем.
   */
  function describe(reason) {
    const found = CHANNEL[reason];
    if (!found) {
      throw new Error(
        `[diag] причина «${reason}» не из словаря оси канала. ` +
        `Допустимые: ${Object.keys(CHANNEL).join(', ')}. ` +
        'Новое имя добавляется в КОНТРАКТЫ.md §4г, а не в код.',
      );
    }
    return found;
  }

  /**
   * Завести докладчика для одного источника.
   *
   * @param {object} cfg
   *   `subject` — чьё это состояние, попадает в строку лога («stats», «orderbook»);
   *   `onError` — необязательный слушатель хоста, зовётся на КАЖДОМ отказе;
   *   `every`   — необязательная замена политики: писать в лог каждый N-й отказ
   *               подряд, а не только первый. Задаётся явно и только там, где
   *               частота этого требует.
   *   `log`     — подмена вывода, нужна тестам; по умолчанию console.
   */
  function reporter(cfg) {
    const subject = (cfg && cfg.subject) || 'diag';
    const onError = cfg && cfg.onError;
    const every = cfg && cfg.every;
    const log = (cfg && cfg.log) || console;

    let kind = null;
    let count = 0;

    return {
      /** Текущее состояние: `null` — всё хорошо, иначе имя причины. */
      state: () => kind,
      /** Сколько отказов подряд одной и той же причины. */
      count: () => count,
      /** Подпись и короткая метка для этой причины. */
      describe,

      /**
       * Отказ. Возвращает `{ badge, why, first }` — виджету остаётся только
       * нарисовать; решать, писать ли в лог, он больше не должен.
       */
      fail(reason, detail) {
        const info = describe(reason);
        const changed = kind !== reason;
        count = changed ? 1 : count + 1;
        kind = reason;

        // По умолчанию — на смене состояния. Поток одинаковых строк читать
        // перестанут так же быстро, как молчание, а подавленная диагностика
        // дороже шумной: поэтому не «реже», а «на переходе».
        const due = changed || (every ? count % every === 0 : false);
        if (due) {
          log.error(`[${subject}] ${info.why} (${reason}), подряд: ${count}`, detail);
        }
        if (onError) onError({ reason, detail, count, first: changed });

        return { badge: info.badge, why: info.why, first: changed };
      },

      /** Успех. Сообщает о восстановлении числом, если отказы были. */
      ok() {
        if (kind) {
          log.info(`[${subject}] обновление восстановлено после ${count} неудач (${kind})`);
        }
        const was = kind;
        kind = null;
        count = 0;
        return was;
      },
    };
  }

  window.Diag = { reporter, describe, CHANNEL };
})();
