'use strict';
// ============================================================================
// Ряд цены и его РАЗРЫВ (TRM-19, Р-073).
//
// Формирующаяся свеча — единственное место в терминале, где из потока сделок
// собирается непрерывность. Поэтому здесь же живёт и понятие, обратное ей:
// **разрыв ряда**.
//
// Смысл решения штаба: смена условий, при которых получена цена, — это НЕ
// продолжение ряда, а начало нового. Склеить их в один бар значит показать
// движение, которого не было ни на одном рынке, — а по этому бару ставят
// стопы и читают график.
//
// Причин разрыва сегодня две, и обе существуют БЕЗ смены источника:
//   * `feed-lost`  — связь с фидом оборвалась (сокет закрылся);
//   * `feed-stale` — фид молчит дольше порога.
// Раньше ни одна из них ряд не прерывала: `formingRaw` переживал обрыв сокета
// целиком, и бар продолжался через дыру любой длины.
//
// Третья причина, `source-change`, заведена здесь ПУСТОЙ сознательно: смена
// источника котировок — та самая, ради которой Р-073 принималось. Терминал
// сегодня берёт цены прямо с биржи и поля `source` не видит вовсе, поэтому
// породить это событие некому. В день переезда на MDS причина подключается
// одной строкой в месте, которое уже названо, — а не ищется заново.
//
// Что делает разрыв:
//   1. **закрывает** формирующуюся свечу — она остаётся на графике такой,
//      какой её наблюдали, но больше НЕ растёт;
//   2. переводит ряд в состояние «разорван»: живые сделки до пересева
//      отбрасываются. Это не потеря данных — то, что произошло в дыре,
//      принесёт авторитетный пересев с сервера (REST), который видел её всю.
//
// Почему не «открыть новый бар прямо сейчас»: в пределах одного интервала у
// нового бара было бы ТО ЖЕ время, а график ключует бары временем — второй
// молча затёр бы первый, и наблюдённое исчезло бы. Ждать пересева честнее,
// чем рисовать правдоподобное.
// ============================================================================

(function () {
  /**
   * Причины разрыва ряда. Имена машинные, kebab-case — как оси причин в §4г.
   *
   * Словарь ЗДЕСЬ, а не у вызывающих: причина, заведённая на месте вызова,
   * не попадает ни в один перечень, и следующий добавит синоним.
   * @type {Readonly<Record<string, string>>}
   */
  var BREAK_REASONS = Object.freeze({
    'feed-lost': 'связь с фидом оборвалась',
    'feed-stale': 'фид молчит дольше порога',
    'source-change': 'сменился источник котировок',
  });

  /**
   * @typedef {{ time: number, open: number, high: number, low: number, close: number, volume: number }} Bar
   * Свеча в raw-единицах шлюза, как её отдаёт `/candles`.
   */

  /**
   * @typedef {{ reason: string, closed: Bar | null }} BreakResult
   */

  /**
   * Завести ряд. Состояние замкнуто внутри: снаружи его не переписать мимо
   * разрыва — ровно та ошибка, из-за которой бар переживал обрыв связи.
   */
  function create() {
    /** @type {Bar | null} */
    var forming = null;
    var lastBarTime = 0;
    var broken = false;
    /** @type {string | null} */
    var breakReason = null;

    /** @param {Bar} b @returns {Bar} */
    function copy(b) {
      return { time: b.time, open: b.open, high: b.high, low: b.low, close: b.close, volume: b.volume };
    }

    return {
      /** Формирующаяся свеча (копия — чтобы её не правили в обход разрыва). @returns {Bar | null} */
      forming: function () {
        return forming ? copy(forming) : null;
      },
      /** @returns {number} */
      lastBarTime: function () {
        return lastBarTime;
      },
      /** Разорван ли ряд: до пересева живые сделки не принимаются. @returns {boolean} */
      isBroken: function () {
        return broken;
      },
      /** Причина последнего разрыва, пока он не снят пересевом. @returns {string | null} */
      breakReason: function () {
        return breakReason;
      },

      /**
       * Пересев ряда авторитетными данными с сервера. **Снимает разрыв**:
       * ответ REST видел и дыру тоже, поэтому после него продолжать можно.
       *
       * @param {Bar | null} bar последняя свеча ответа, либо null — ответ пуст
       */
      seed: function (bar) {
        broken = false;
        breakReason = null;
        if (!bar) {
          forming = null;
          lastBarTime = 0;
          return;
        }
        forming = copy(bar);
        lastBarTime = bar.time;
      },

      /**
       * Живая сделка.
       *
       * @param {{ now: number, tf: number, price: number, qty: number }} t
       *   `now` — секунды; передаётся снаружи, чтобы агрегатор остался чистым
       *   и проверяемым без подмены часов.
       * @returns {Bar | null} свеча к перерисовке, либо null — рисовать нечего
       */
      onTrade: function (t) {
        // Ряд разорван: продолжать нечем. Именно здесь раньше бар склеивался
        // через дыру — сделка после обрыва дописывалась в бар до обрыва.
        if (broken) return null;
        var b = t.now - (t.now % t.tf);
        if (!forming || b > forming.time) {
          forming = { time: b, open: t.price, high: t.price, low: t.price, close: t.price, volume: t.qty };
        } else if (b < forming.time) {
          // Сделка из прошлого интервала (переподключение, перепутанный порядок):
          // в текущий бар ей нельзя — она сдвинула бы его границы задним числом.
          return null;
        } else {
          forming.high = Math.max(forming.high, t.price);
          forming.low = Math.min(forming.low, t.price);
          forming.close = t.price;
          // Объём свечи по определению — СУММА количеств всех сделок интервала
          // (TRM-32). Здесь стояло присваивание при открытии бара и больше
          // ничего: поле звалось «объём», а хранило количество ПЕРВОЙ сделки.
          // Отсутствующее поле ищут, лгущее — читают как правду.
          //
          // Накопление поверх пересева двойным счётом не является: `seed`
          // кладёт авторитетное значение биржи на момент снимка, а сюда
          // попадают сделки, увиденные ПОСЛЕ него. Перекрытие возможно лишь
          // на сделках в доли секунды около снимка и снимается следующим же
          // пересевом — он не прибавляет, а замещает.
          forming.volume += t.qty;
        }
        if (forming.time < lastBarTime) return null;
        lastBarTime = forming.time;
        return copy(forming);
      },

      /**
       * Разрыв ряда. Закрывает формирующуюся свечу и останавливает рост.
       *
       * Идемпотентен: второй разрыв подряд не стирает уже закрытую свечу —
       * обрыв и протухание приходят парой, и вторая причина не должна
       * отменять то, что наблюдали до первой.
       *
       * @param {string} reason одна из {@link BREAK_REASONS}
       * @returns {BreakResult}
       */
      markBreak: function (reason) {
        if (!Object.prototype.hasOwnProperty.call(BREAK_REASONS, reason)) {
          // Своё имя на месте вызова — это синоним в обход словаря.
          throw new Error('неизвестная причина разрыва ряда: ' + reason);
        }
        var closed = forming ? copy(forming) : null;
        if (!broken) {
          broken = true;
          breakReason = reason;
        }
        return { reason: reason, closed: closed };
      },
    };
  }

  window.Series = { create: create, BREAK_REASONS: BREAK_REASONS };
})();
