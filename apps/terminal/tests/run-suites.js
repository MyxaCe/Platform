'use strict';
/* ============================================================================
 * run-suites.js — запуск наборов тестов с РАЗЛИЧИМЫМ исходом (TRM-26).
 *
 * ЗАЧЕМ. Один прогон из примерно десяти завершился кодом 1 **без единого
 * красного теста и без итоговой сводки**: процесс набора умер, а не тест упал.
 * Причину найти не удалось, и главное в этом — не гонка, а то, что снаружи
 * «набор отработал и дал отказы» и «набор не отработал» выглядели одинаково.
 *
 * Пока эти два исхода неразличимы, каждый следующий такой случай снова
 * останется без причины: смотреть будет не на что. Это наш же класс —
 * невыполнившаяся проверка обязана быть отличима от пройденной.
 *
 * ЧТО ДЕЛАЕТ. Запускает наборы по одному, передаёт их вывод как есть и в
 * конце печатает исход КАЖДОГО набора одним из трёх слов:
 *
 *   пройден       — сводка есть, отказов нет, код 0;
 *   отказы        — сводка есть, отказы названы числом;
 *   НЕ ОТРАБОТАЛ  — сводки нет: процесс умер. Печатается код выхода, сигнал
 *                   и хвост потока ошибок. Это НЕ «упал тест» и не успех:
 *                   результат набора неизвестен.
 *
 * Код выхода тоже различает исходы: 1 — отказы в тестах, 2 — набор не
 * отработал. Одинаковый код скрыл бы ровно ту разницу, ради которой это
 * написано.
 * ========================================================================== */
const { spawn } = require('node:child_process');

/** Наборы в порядке запуска. Состав прогона — здесь, а не в шаблоне путей. */
const SUITES = [
  { name: 'модульные', args: ['--test', 'tests/*.test.js'] },
  { name: 'браузерные', args: ['--test', '--test-concurrency=1', 'tests/browser/*.test.js'] },
];

/** Сводка `node --test`: по ней и только по ней видно, что набор доработал. */
const TESTS_RE = /^ℹ tests (\d+)/gm;
const FAIL_RE = /^ℹ fail (\d+)/gm;

/**
 * ПОСЛЕДНЕЕ совпадение, а не первое.
 *
 * Внутри набора может запуститься дочерний прогон — у нас это проверки самого
 * запускателя, — и он печатает СВОЮ сводку раньше родительской. Первое
 * совпадение поэтому принадлежит чужому набору.
 *
 * Поймано не рассуждением: после добавления своих же проверок запускатель
 * объявил «модульные: пройден — 1» вместо 177, то есть занизил охват на 176
 * тестов и выглядел при этом совершенно спокойно. Объявленный числом охват
 * честен ровно настолько, насколько верно сосчитано то, что считают.
 */
function lastMatch(output, re) {
  re.lastIndex = 0;
  let found = null;
  let m = re.exec(output);
  while (m) {
    found = m;
    m = re.exec(output);
  }
  return found;
}

/**
 * Исход набора по его выводу и коду возврата — отдельно от запуска, чтобы его
 * можно было проверить, не поднимая браузер.
 *
 * Правило одно: **судим по сводке, а не по коду возврата.** Код говорит «что-то
 * не так», сводка говорит «набор доработал». Без неё любой ненулевой код
 * читался бы как «упал тест», а это ровно та подмена, из-за которой случай
 * остался без причины.
 */
function classify(output, code, signal) {
  const tests = lastMatch(output, TESTS_RE);
  const fails = lastMatch(output, FAIL_RE);

  if (!tests || !fails) {
    return {
      outcome: 'НЕ ОТРАБОТАЛ',
      code,
      signal,
      why: 'итоговой сводки в выводе нет — процесс не дошёл до конца',
    };
  }

  const failed = Number(fails[1]);
  return {
    // Ненулевой код при нулевых отказах тоже не успех: набор доработал, но
    // что-то вне тестов пошло не так, и молчать об этом нельзя.
    outcome: failed > 0 || code !== 0 ? 'отказы' : 'пройден',
    count: Number(tests[1]),
    failed,
    code,
    signal,
  };
}

function runSuite(suite) {
  return new Promise((resolve) => {
    // Без `shell: true`: node сам разворачивает шаблоны путей, а оболочка
    // здесь добавляла бы склейку аргументов без экранирования — node об этом
    // прямо предупреждает.
    //
    // `NODE_TEST_CONTEXT` снимаем намеренно. Node ставит её своим детям, и
    // набор, запущенный из-под другого набора, переключает вывод на формат
    // для вложенных прогонов — без той самой сводки, по которой мы судим об
    // исходе. Без этой строки запускатель отвечал бы по-разному в
    // зависимости от того, кто его позвал, а инструмент, чей ответ зависит от
    // вызывающего, ничего не измеряет. Нашлось собственным тестом.
    const env = Object.assign({}, process.env);
    delete env.NODE_TEST_CONTEXT;

    const child = spawn(process.execPath, suite.args, { env });

    let stdout = '';
    let stderr = '';
    child.stdout.on('data', (c) => { stdout += c; process.stdout.write(c); });
    child.stderr.on('data', (c) => { stderr += c; process.stderr.write(c); });

    child.on('error', (e) => {
      resolve({ suite, outcome: 'НЕ ОТРАБОТАЛ', code: null, signal: null, why: String(e), stderr });
    });

    child.on('close', (code, signal) => {
      resolve(Object.assign({ suite, stderr }, classify(stdout + stderr, code, signal)));
    });
  });
}

/**
 * Код возврата по исходам наборов.
 *
 * Разные коды у разных бед — часть смысла этого запускателя: одинаковый код
 * снова склеил бы «тест упал» и «набор не отработал», то есть вернул бы нас
 * туда, откуда задача началась. 2 перевешивает 1: неизвестный результат хуже
 * известного отказа — упавший тест мы видим и чиним, а неизвестный сначала
 * надо сделать известным.
 */
function exitCodeFor(results) {
  let worst = 0;
  for (const r of results) {
    if (r.outcome === 'НЕ ОТРАБОТАЛ') worst = Math.max(worst, 2);
    else if (r.outcome === 'отказы') worst = Math.max(worst, 1);
  }
  return worst;
}

async function main() {
  const results = [];
  for (const suite of SUITES) {
    results.push(await runSuite(suite));
  }

  process.stdout.write('\n==================== исход наборов ====================\n');

  for (const r of results) {
    if (r.outcome === 'НЕ ОТРАБОТАЛ') {
      process.stdout.write(
        `  ${r.suite.name}: НЕ ОТРАБОТАЛ — ${r.why}\n` +
        `      код выхода: ${r.code}, сигнал: ${r.signal ?? 'нет'}\n` +
        '      Результат набора НЕИЗВЕСТЕН: это не «тесты прошли» и не «тест упал».\n',
      );
      const tail = String(r.stderr || '').trim().split('\n').slice(-12);
      if (tail.length && tail[0]) {
        process.stdout.write('      хвост потока ошибок:\n');
        for (const line of tail) process.stdout.write(`        ${line}\n`);
      } else {
        process.stdout.write('      поток ошибок пуст — процесс умер молча\n');
      }
      continue;
    }

    if (r.outcome === 'отказы') {
      process.stdout.write(
        `  ${r.suite.name}: отказы — ${r.failed} из ${r.count} (код выхода ${r.code})\n`,
      );
      continue;
    }

    process.stdout.write(`  ${r.suite.name}: пройден — ${r.count}\n`);
  }

  process.stdout.write('=======================================================\n');
  process.exit(exitCodeFor(results));
}

if (require.main === module) {
  main();
}

module.exports = { classify, runSuite, exitCodeFor, SUITES };
