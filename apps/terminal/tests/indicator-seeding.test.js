'use strict';
// ============================================================================
// Затравка сглаживания у производных индикаторов (TRM-23).
//
// AC, Force Index и сигнальная линия MACD считаются поверх другого индикатора,
// у которого первые значения не определены. Раньше пропуск подменялся нулём, и
// сглаживание получало частокол выдуманных нулей перед настоящими данными.
// Результат считался частично из выдумки **и показывался** как результат.
//
// ЭТАЛОН ВЗЯТ ИЗ ОПРЕДЕЛЕНИЯ, А НЕ ИЗ РЕАЛИЗАЦИИ. Здесь три независимых друг
// от друга способа, и ни один не снят с нашего кода:
//
//   1) ЧИСЛА, посчитанные руками по формуле на ряде, где арифметику видно
//      глазами (k = 2/3 при p = 2);
//   2) ИНВАРИАНТ СДВИГА: сколько пропусков ни припиши в начало ряда, значения
//      на совпадающих местах обязаны не измениться. Выдуманный ноль этот
//      инвариант ломает — в этом и состояла ошибка;
//   3) ПЕРВЫЙ ОПРЕДЕЛЁННЫЙ ИНДЕКС, выведенный из определения арифметикой
//      задержек, а не подсмотренный в выводе.
//
// Третий способ важнее первых двух: он ловит «посчитали раньше, чем имели
// право», а именно это и показывалось человеку как сигнал.
// ============================================================================
const test = require('node:test');
const assert = require('node:assert/strict');
const { loadModule } = require('./helpers/load-module');

const I = loadModule('indicators.js', 'Indicators');

/**
 * Ряд, который ЕСТЬ ЧЕМ сломать: цена и растёт и падает, есть разрывы к
 * предыдущему значению, объёмы разные. Вырожденный ряд (монотонный или с
 * постоянным объёмом) дал бы зелёное при любой формуле.
 */
function series(n) {
  const out = [];
  let price = 100;
  for (let i = 0; i < n; i++) {
    const step = Math.sin(i / 3) * 4 + (i % 7 === 0 ? -6 : 1.5);
    const open = price;
    price = Math.round((price + step) * 100) / 100;
    out.push({
      time: 1700000000 + i * 60,
      open,
      high: Math.max(open, price) + 1.25,
      low: Math.min(open, price) - 1.25,
      close: price,
      volume: 100 + ((i * 37) % 53),
    });
  }
  return out;
}

const CS = series(60);
const CLOSES = CS.map((c) => c.close);

/** Индекс первого значения, которое индикатор счёл определённым. */
const firstDefined = (arr) => arr.findIndex((x) => x != null);

// ---- 1. Числа из формулы, проверяемые глазами ------------------------------

test('EMA считается по рекурренте, и затравка — первое значение ряда', () => {
  // p = 2 → k = 2/(2+1) = 2/3. Ряд [1, 2, 3]:
  //   e0 = 1                                (затравка)
  //   e1 = 2·(2/3) + 1·(1/3) = 4/3 + 1/3 = 5/3
  //   e2 = 3·(2/3) + (5/3)·(1/3) = 2 + 5/9 = 23/9
  // Выдача начинается с индекса p−1 = 1.
  const out = I.ema([1, 2, 3], 2);

  assert.equal(out[0], null, 'до p−1 значения нет');
  assert.ok(Math.abs(out[1] - 5 / 3) < 1e-12, `ожидали 5/3, получили ${out[1]}`);
  assert.ok(Math.abs(out[2] - 23 / 9) < 1e-12, `ожидали 23/9, получили ${out[2]}`);
});

// ---- 2. Свойство, которого у EMA НЕТ, и почему ---------------------------

test('инвариант сдвига к EMA неприменим — записано, чтобы его не «дозакрыли»', () => {
  // Первая редакция этих тестов проверяла: отрежь десять баров истории —
  // значения на совпадающих барах не изменятся. Проверка покраснела, и права
  // была она, а не я: EMA — фильтр с бесконечной памятью, её значение зависит
  // от ВСЕЙ предыдущей истории, затухающей, но не исчезающей. Для SMA
  // инвариант верен, для EMA — нет, и это свойство определения, а не дефект.
  //
  // Записано здесь, потому что проверка выглядела убедительно и следующий
  // напишет её снова. Настоящая защита от выдуманных нулей — равенство с EMA
  // ОПРЕДЕЛЁННОЙ ЧАСТИ ряда, и она ниже.
  const long = I.macdFull(CLOSES)[1];
  const short = I.macdFull(CLOSES.slice(10))[1];

  const i = CLOSES.length - 1;
  assert.notEqual(
    long[i],
    short[i - 10],
    'если значения совпали, EMA перестала быть EMA — проверь затравку',
  );
});

// ---- 3. Первый определённый индекс — из арифметики задержек ----------------

test('MACD: линия с 25-го бара, сигнальная — с 33-го', () => {
  // EMA(p) определена с индекса p−1. Линия = EMA12 − EMA26 → max(11, 25) = 25.
  // Сигнальная = EMA(линии, 9) → 25 + (9−1) = 33.
  // Раньше сигнальная появлялась на 25-м: на восемь баров раньше, чем имела
  // право, и эти восемь были посчитаны из нулей, которых не существовало.
  const [line, sig] = I.macdFull(CLOSES);

  assert.equal(firstDefined(line), 25, 'MACD-линия');
  assert.equal(firstDefined(sig), 33, 'сигнальная линия');
});

test('AC: с 37-го бара, а не с 33-го', () => {
  // AO = SMA(медианной цены, 5) − SMA(…, 34) → определено с 33.
  // AC = AO − SMA(AO, 5) → 33 + (5−1) = 37.
  const ac = I.acOsc(CS);

  assert.equal(firstDefined(I.ao(CS)), 33, 'AO');
  assert.equal(firstDefined(ac), 37, 'AC');
});

test('Force Index: с p-го бара', () => {
  // FI(1) определён с 1-го бара (нужна предыдущая цена закрытия).
  // FI(p) = EMA(FI(1), p) → 1 + (p−1) = p.
  for (const p of [2, 5, 13]) {
    assert.equal(firstDefined(I.forceIndex(CS, p)), p, `период ${p}`);
  }
});

// ---- 4. Сигнальная равна EMA определённой части линии ----------------------

test('сигнальная MACD — это EMA самой линии, а не линии с дописанными нулями', () => {
  // Эталон собран ДРУГИМ путём: берём определённую часть линии и считаем её
  // EMA уже проверенной `ema`. Это буквальное прочтение определения
  // «сигнальная = EMA(MACD, 9)» и другой код, чем у проверяемого.
  const [line, sig] = I.macdFull(CLOSES);
  const start = firstDefined(line);
  const reference = I.ema(line.slice(start), 9);

  let compared = 0;
  for (let i = start; i < line.length; i++) {
    const expected = reference[i - start];
    if (expected == null) {
      assert.equal(sig[i], null, `бар ${i}: значения быть не должно`);
      continue;
    }
    assert.ok(Math.abs(sig[i] - expected) < 1e-9, `бар ${i}: ${sig[i]} против ${expected}`);
    compared += 1;
  }
  assert.ok(compared >= 10, `сравнивать было нечего, совпавших баров ${compared}`);
});

test('AC — это AO минус SMA определённой части AO', () => {
  const ao = I.ao(CS);
  const ac = I.acOsc(CS);
  const start = firstDefined(ao);
  const reference = I.sma(ao.slice(start), 5);

  let compared = 0;
  for (let i = start; i < ao.length; i++) {
    const s = reference[i - start];
    if (s == null) {
      assert.equal(ac[i], null, `бар ${i}: значения быть не должно`);
      continue;
    }
    assert.ok(Math.abs(ac[i] - (ao[i] - s)) < 1e-9, `бар ${i}`);
    compared += 1;
  }
  assert.ok(compared >= 10, `сравнивать было нечего, совпавших баров ${compared}`);
});

test('Force Index — это EMA определённой части ряда импульсов', () => {
  // Тот же приём, что у сигнальной MACD: эталон собран другим путём — берём
  // определённую часть ряда и считаем её EMA уже проверенной `ema`.
  const p = 13;
  const fi = I.forceIndex(CS, p);
  const raw = CS.map((c, i) => (i === 0 ? null : (c.close - CS[i - 1].close) * c.volume));
  const reference = I.ema(raw.slice(1), p);

  let compared = 0;
  for (let i = 1; i < CS.length; i++) {
    const expected = reference[i - 1];
    if (expected == null) {
      assert.equal(fi[i], null, `бар ${i}: значения быть не должно`);
      continue;
    }
    assert.ok(Math.abs(fi[i] - expected) < 1e-9, `бар ${i}: ${fi[i]} против ${expected}`);
    compared += 1;
  }
  assert.ok(compared >= 10, `сравнивать было нечего, совпавших баров ${compared}`);
});

// ---- 5. Вырожденные входы --------------------------------------------------

test('ряд короче периода не выдумывает значений', () => {
  // Сравниваем длины, а не массивы: объекты приходят из песочницы `vm`, то
  // есть из ДРУГОГО realm, и `deepEqual` падает на прототипе при совпадающем
  // содержимом. Та же грабля, что у jsdom, и она описана в харнессе.
  assert.equal(I.macdFull(CLOSES.slice(0, 20))[1].filter((x) => x != null).length, 0);
  assert.equal(I.acOsc(CS.slice(0, 20)).filter((x) => x != null).length, 0);
  assert.equal(I.forceIndex(CS.slice(0, 3), 13).filter((x) => x != null).length, 0);
});

test('данные для этих проверок не вырождены', () => {
  // Монотонный ряд или ряд без разрывов дал бы зелёное при любой формуле:
  // осциллятор упёрся бы в границу и перестал различать.
  const ups = CLOSES.filter((c, i) => i > 0 && c > CLOSES[i - 1]).length;
  const downs = CLOSES.filter((c, i) => i > 0 && c < CLOSES[i - 1]).length;
  const volumes = new Set(CS.map((c) => c.volume));

  assert.ok(ups >= 10, `рост должен встречаться, его ${ups}`);
  assert.ok(downs >= 10, `падение должно встречаться, его ${downs}`);
  assert.ok(volumes.size >= 10, `объёмы должны различаться, их ${volumes.size}`);
});

