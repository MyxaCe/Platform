test('мутация «дыру в середине ряда заглаживать молча» здесь непрогоняема', () => {
  // `emaFrom` останавливается на пропуске В СЕРЕДИНЕ ряда, а не перешагивает
  // его. Покрасить эту ветку нечем: все три потребителя (AO, MACD-линия, ряд
  // импульсов) дают пропуски только в начале, а сам помощник наружу не
  // экспортируется — открыть его ради одного теста значило бы расширить
  // поверхность модуля ради проверки входа, которого не бывает.
  //
  // Выбор назван вслух, потому что он НЕ очевиден: перешагнуть дыру выглядит
  // «терпимее». Но сглаженное через дыру значение ничем не отличается на вид
  // от честного — это снова результат, посчитанный из того, чего нет. Если у
  // какого-то индикатора появятся внутренние пропуски, сюда надо вернуться и
  // решить заново, а не обнаружить, что за нас уже решили.
  assert.ok(true);
});
