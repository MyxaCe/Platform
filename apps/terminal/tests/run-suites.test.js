'use strict';
// ============================================================================
// Проверки самого запускателя наборов (TRM-26).
//
// Инструмент проверки проверяют отдельно от того, что он проверяет. Этот
// запускатель существует ради одного различия — «набор отработал и дал
// отказы» против «набор не отработал», — и если ошибётся именно оно, мы
// снова получим случай без причины и не узнаем об этом.
//
// У нас уже есть два повода не доверять инструментам на слово: мутационный
// харнесс дважды печатал «0 красных», не сделав работы, и проверка типов
// выглядела зелёной, не проверяя почти ничего.
// ============================================================================
const test = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');

const { classify, runSuite, exitCodeFor } = require('./run-suites');

/** Сводка `node --test` в том виде, в каком она приходит. */
/** Перевод строки отдельной константой: эти тесты склеивают выводы наборов. */
const NL = '\n';

function summary(tests, fail) {
  return [
    'ℹ tests ' + tests,
    'ℹ suites 0',
    'ℹ pass ' + (tests - fail),
    'ℹ fail ' + fail,
    'ℹ cancelled 0',
  ].join('\n');
}

// ---- Три исхода различаются --------------------------------------------

test('сводка без отказов и нулевой код — пройден', () => {
  const r = classify(summary(17, 0), 0, null);
  assert.equal(r.outcome, 'пройден');
  assert.equal(r.count, 17);
});

test('сводка с отказами — отказы, и их число названо', () => {
  const r = classify(summary(17, 3), 1, null);
  assert.equal(r.outcome, 'отказы');
  assert.equal(r.failed, 3);
  assert.equal(r.count, 17);
});

test('сводки нет — НЕ ОТРАБОТАЛ, и это не отказ теста', () => {
  // Тот самый исход, из-за которого задача и заведена. Смешать его с «упал
  // тест» значит потерять единственный признак, по которому случай можно
  // будет разобрать.
  const r = classify('что-то вывалилось и оборвалось', 1, null);
  assert.equal(r.outcome, 'НЕ ОТРАБОТАЛ');
  assert.equal(r.code, 1);
  assert.match(r.why, /сводки/);
});

test('пустой вывод — тоже НЕ ОТРАБОТАЛ, а не «нечего проверять»', () => {
  const r = classify('', null, 'SIGKILL');
  assert.equal(r.outcome, 'НЕ ОТРАБОТАЛ');
  assert.equal(r.signal, 'SIGKILL');
});

test('сводка есть, отказов нет, но код ненулевой — не успех', () => {
  // Набор доработал, а что-то вне тестов пошло не так: висящий таймер,
  // падение при уборке. Признать это пройденным значило бы завести себе
  // третий молчаливый исход вместо двух различимых.
  const r = classify(summary(17, 0), 7, null);
  assert.equal(r.outcome, 'отказы');
});

test('обрыв на полуслове не считается сводкой', () => {
  // Вывод оборвался после первой строки сводки: число тестов есть, числа
  // отказов нет. Прочитать это как «ноль отказов» — ровно та подмена,
  // которую мы ловим.
  const r = classify('ℹ tests 17\nℹ suites 0\n', 1, null);
  assert.equal(r.outcome, 'НЕ ОТРАБОТАЛ');
});

test('вложенный прогон не подменяет охват своим числом', () => {
  // Нашлось не рассуждением, а собственным прогоном: добавив сюда проверки
  // запускателя, я получил «модульные: пройден — 1» вместо 177. Внутренний
  // набор печатает свою сводку раньше родительской, и первое совпадение
  // принадлежит чужому набору.
  //
  // Охват, объявленный числом, честен ровно настолько, насколько верно
  // сосчитано то, что считают, — а заниженный выглядит так же спокойно.
  const nested = [summary(1, 0), '', summary(177, 0)].join(NL);
  const r = classify(nested, 0, null);

  assert.equal(r.outcome, 'пройден');
  assert.equal(r.count, 177, 'взять надо последнюю сводку, свою, а не первую');
});

test('вложенные отказы не выдаются за свои', () => {
  // Обратная сторона: дочерний набор упал, родительский прошёл. Судить надо
  // по своей сводке, иначе чужой отказ станет нашим и наоборот.
  const nested = [summary(1, 1), '', summary(177, 0)].join(NL);
  assert.equal(classify(nested, 0, null).outcome, 'пройден');

  const inverse = [summary(1, 0), '', summary(177, 2)].join(NL);
  assert.equal(classify(inverse, 1, null).outcome, 'отказы');
  assert.equal(classify(inverse, 1, null).failed, 2);
});

test('у «не отработал» и «отказы» разные коды возврата', () => {
  // Если склеить их в один код, CI снова не отличит «тест упал» от «набор не
  // запустился» — то есть вернёт нас ровно туда, откуда задача началась.
  const dead = [{ outcome: 'НЕ ОТРАБОТАЛ' }];
  const failed = [{ outcome: 'отказы' }];
  const ok = [{ outcome: 'пройден' }];

  assert.equal(exitCodeFor(ok), 0);
  assert.equal(exitCodeFor(failed), 1);
  assert.equal(exitCodeFor(dead), 2);
  assert.notEqual(exitCodeFor(dead), exitCodeFor(failed));
});

test('неизвестный результат перевешивает известный отказ', () => {
  // Набор, который не отработал, важнее упавшего теста: упавший тест мы
  // видим и чиним, а неизвестный результат сначала надо сделать известным.
  assert.equal(exitCodeFor([{ outcome: 'отказы' }, { outcome: 'НЕ ОТРАБОТАЛ' }]), 2);
  assert.equal(exitCodeFor([{ outcome: 'НЕ ОТРАБОТАЛ' }, { outcome: 'отказы' }]), 2);
});

test('формат вывода закрепляет сам запускатель, а не записи наборов', () => {
  // Без этого node выбирает формат по тому, терминал на выходе или труба, и
  // запускатель читал бы TAP вместо сводки — то есть объявлял бы здоровый
  // набор не отработавшим.
  //
  // Проверяем, что решение живёт В ОДНОМ месте: первая редакция поручала его
  // каждой записи набора, и мои же проверки его не прописали. Решение,
  // которое должны помнить все вызывающие, однажды забудут.
  const { REPORTER, SUITES } = require('./run-suites');

  assert.ok(
    REPORTER.some((a) => String(a).startsWith('--test-reporter=')),
    'запускатель обязан закреплять формат',
  );
  for (const s of SUITES) {
    assert.ok(
      !s.args.some((a) => String(a).startsWith('--test-reporter')),
      `запись «${s.name}» дублирует решение о формате — оно должно быть одно`,
    );
  }
});

test('набор в трубе отчитывается так же, как в терминале', async () => {
  // Зеркало к предыдущей: проверяем не настройку, а её следствие. Дочерний
  // процесс всегда получает трубу, значит именно этот путь и ломался.
  const path = require('node:path');
  const one = path.join(__dirname, 'fixtures', 'one-passing.test.js');
  const r = await runSuite({ name: 'в трубе', args: ['--test'], files: [one] });

  assert.equal(r.outcome, 'пройден', 'в трубе исход обязан читаться так же');
  assert.equal(r.count, 1);
});

// ---- И то же самое на настоящем процессе -----------------------------------

test('набор, который не запустился, назван НЕ ОТРАБОТАВШИМ (живой процесс)', async () => {
  // Разбор строк проверен выше; здесь проверяется, что исход доезжает от
  // настоящего умершего процесса, а не только от придуманной строки.
  const one = path.join(__dirname, 'fixtures', 'one-passing.test.js');
  const r = await runSuite({ name: 'заведомо негодный', args: ['--test', '--негодный-флаг'], files: [one] });

  assert.equal(r.outcome, 'НЕ ОТРАБОТАЛ');
  assert.notEqual(r.code, 0, 'код возврата обязан быть ненулевым');
  assert.match(String(r.stderr), /bad option|негодный/i, 'поток ошибок обязан дойти до отчёта');
});

test('здоровый набор на живом процессе назван пройденным', async () => {
  // Зеркало предыдущего: без него «всегда НЕ ОТРАБОТАЛ» выглядело бы так же
  // зелено, а запускатель, который всё подряд объявляет мёртвым, бесполезен
  // ровно так же, как тот, что всё объявляет живым.
  const one = path.join(__dirname, 'fixtures', 'one-passing.test.js');
  const r = await runSuite({ name: 'здоровый', args: ['--test'], files: [one] });

  assert.equal(r.outcome, 'пройден');
  assert.equal(r.failed, 0);
  assert.ok(r.count >= 1);
});

test('каталог без тестов — НЕ ОТРАБОТАЛ, а не «ноль отказов»', async () => {
  // Третий дефект, найденный прогоном на Linux: node до 22-й версии не
  // разворачивает шаблоны путей сам, и набор молча переставал существовать.
  // «Запускать нечего» обязано отличаться от «всё прошло» — иначе удалённый
  // или переименованный каталог читается как успех.
  const r = await runSuite({ name: 'пустой', dir: 'tests/нет-такого-каталога', args: ['--test'] });

  assert.equal(r.outcome, 'НЕ ОТРАБОТАЛ');
  assert.match(r.why, /не найдено ни одного файла/);
});

test('наборы находят свои файлы, и их не ноль', () => {
  // Зеркало к проверке пустого каталога: запускатель, который всё объявляет
  // пустым, бесполезен ровно так же. Заодно охват объявлен числом — исчезни
  // каталог или поменяйся имя, это будет видно сразу.
  const { SUITES, filesIn } = require('./run-suites');

  for (const s of SUITES) {
    const found = filesIn(s.dir);
    assert.ok(found.length > 0, `набор «${s.name}»: в ${s.dir} не найдено файлов`);
    assert.ok(found.every((f) => f.endsWith('.test.js')), `набор «${s.name}»: попало лишнее`);
  }
});
