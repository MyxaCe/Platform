#!/usr/bin/env bash
# ============================================================================
# Держатель тома сборочных артефактов (TRM-39, Р-030 расширено 21.10).
#
# ЗАЧЕМ. `terminal-target` выглядит кешем: к работающему контейнеру он не
# присоединён, `docker system df` считает его освобождаемым, и первая же
# уборка «ничего не используется» его снесёт. Вернуть содержимое можно только
# холодной сборкой: 3,6 ГБ артефактов, а сама сборка 20.10 увела свободное
# место с 21 ГБ до 11 и почти остановила работу.
#
# ПОЧЕМУ НЕ МЕТКА. У локального тома метки (`label`) выставляются ТОЛЬКО при
# создании; `docker volume update` работает лишь с кластерными томами, а
# пересоздание уничтожит ровно то, что мы бережём. Отфильтровать том из
# `prune` по метке, пока он существует, невозможно.
#
# ПОЧЕМУ ДЕРЖАТЕЛЬ РАБОТАЕТ. `docker volume prune` удаляет тома, не
# используемые НИ ОДНИМ контейнером — включая остановленные и созданные.
# Созданный и никогда не запускаемый контейнер держит ссылку, и том
# перестаёт быть ничейным: из `prune` он выпадает, а в `docker system df`
# перестаёт числиться освобождаемым. Это препятствие, а не записка: записку
# видит открывший том, а не тот, кто сносит по списку.
#
# Чего держатель НЕ переживёт: `docker system prune -a` снимает остановленные
# контейнеры, и после этого том снова станет ничейным. Эти команды у нас
# запрещены отдельно (Р-030), и держатель их запрет не заменяет.
#
# Скрипт идемпотентен: повторный запуск ничего не меняет.
# ============================================================================
set -euo pipefail

VOLUME="terminal-target"
# Имя обязано объяснять себя: его увидят в списке контейнеров люди, которые о
# нашей переписке не знают. Латиница — требование Docker к именам.
KEEPER="do-not-remove--holds-${VOLUME}--cold-rebuild-3.6gb"
# Образ берём уже имеющийся, чтобы ничего не тянуть из сети.
IMAGE="rust:slim"

if ! docker info >/dev/null 2>&1; then
  echo "[keep-build-volume] Docker не отвечает — держатель НЕ создан." >&2
  exit 1
fi

if docker container inspect "${KEEPER}" >/dev/null 2>&1; then
  echo "[keep-build-volume] держатель уже есть: ${KEEPER}"
else
  MSYS_NO_PATHCONV=1 docker create \
    --name "${KEEPER}" \
    --label "purpose=Держит том ${VOLUME} от уборки: том выглядит кешем, но его потеря стоит холодной сборки" \
    --label "cost=3.6 ГБ артефактов; восстановление — холодная сборка; 20.10 она увела свободное место с 21 ГБ до 11" \
    --label "decision=Р-030 (расширено 21.10), задача TRM-39" \
    --label "never-runs=Контейнер создан и никогда не запускается; он нужен только как ссылка на том" \
    -v "${VOLUME}:/target:ro" \
    "${IMAGE}" \
    sh -c 'echo "Этот контейнер не предназначен для запуска. Он держит том terminal-target от уборки (TRM-39)."' \
    >/dev/null
  echo "[keep-build-volume] держатель создан: ${KEEPER}"
fi

# Проверяем РЕЗУЛЬТАТ, а не факт выполнения команды: том обязан перестать
# числиться ничейным, иначе держатель бесполезен и об этом надо сказать.
if docker volume ls --filter dangling=true --format '{{.Name}}' | grep -qx "${VOLUME}"; then
  echo "[keep-build-volume] ⚠️ том ${VOLUME} ВСЁ ЕЩЁ числится ничейным — держатель не сработал" >&2
  exit 1
fi
echo "[keep-build-volume] том ${VOLUME} больше не числится ничейным — prune его не тронет"
