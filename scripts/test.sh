#!/usr/bin/env bash
# Прогон проверок Rust-workspace (backend/) через Docker-образ Rust (ADR-004).
# Кэш сборки и реестра crates.io — в именованных volume'ах (первый прогон медленный).
# Тома переименованы под текущий проект (были platform-target/platform-registry от
# допивотного репозитория). Старые НЕ удалены — решение по ним за владельцем; из-за
# смены имени первый прогон после этой правки собирает всё заново.
#
# ⚠️ `terminal-target` УБОРКОЙ НЕ ТРОГАТЬ (Р-030, расширено 21.10). Он выглядит
# кешем и считается освобождаемым, потому что не присоединён к работающему
# контейнеру, — но вернуть его содержимое можно только холодной сборкой, а она
# 20.10 увела свободное место с 21 ГБ до 11. Тёплые прогоны стоят около нуля:
# вся цена в первом. Подробно — в docs/06-operations.md и в файле
# `00-НЕ-УДАЛЯТЬ-ЦЕНА-ПОТЕРИ.txt` внутри самого тома.
#
# Контракты CMS (TRM-15, Р-058). Эталонная таблица случаев видимости лежит в
# чужом репозитории, и у нас есть её копия. Копия без сверки — седьмой
# производный список, поэтому тест сверяет её с источником по содержимому, а
# источник надо ему дать: репозитории разные, общего дерева у них нет.
# Монтируется **только на чтение** — чужая папка, править её мы не вправе.
# Если каталога нет, переменная не задаётся вовсе, и тест сверки падает с
# «сверка НЕ выполнена»: непроверенное не должно выглядеть пройденным.
#
# СОСТАВ ПРОВЕРОК (TRM-29, QA-10). Здесь идут ТЕ ЖЕ проверки и в том же порядке,
# что в CI: тесты Rust, clippy, формат — и ФРОНТ (`npm test`: типы, модульные,
# браузерные).
#
# Фронта здесь не было вовсе (QA-10). Правило этого файла — «проверка, которую
# гоняют только в CI, обнаруживается отказом в CI» — было записано тут же, но
# относилось только к Rust: целый прогон из 232 проверок жил исключительно в
# CI. Зеркало QA-09 с другой стороны: там прогон не видел живой базы, здесь —
# не видел фронта. В обоих случаях зелёный ответ был честным и отвечал на
# вопрос уже заявленного.
# Раньше тут был только `cargo test`, а clippy жил исключительно в CI — и
# закономерно нашёлся отказом в CI (TRM-27): позже всего и чужими глазами.
# Проверка, которую гоняют только в CI, обнаруживается отказом в CI.
# Поэтому пропуска отдельных шагов здесь нет намеренно: переключатель вроде
# SKIP_CLIPPY однажды выставят и забудут, и мы вернёмся ровно сюда.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

# Хуки репозитория — здесь, а не в чьей-то памяти (QA-08).
#
# `.git/hooks` не версионируется, поэтому хук, который каждый ставит руками,
# стоит у того, кто и так помнит. Прогон запускают все, значит установка живёт
# в нём: одна строка, идемпотентная, без вывода при успехе.
git -C "${ROOT}" config core.hooksPath scripts/hooks 2>/dev/null || true

if ! docker info >/dev/null 2>&1; then
  echo "[test.sh] Docker не отвечает — проверки НЕ выполнены (это не 'зелено')." >&2
  echo "[test.sh] Запустите Docker Desktop и повторите." >&2
  exit 1
fi

CMS_CONTRACTS="${CMS_CONTRACTS:-${ROOT}/../cms/src/contracts}"
CONTRACTS_ARGS=()
if [ -d "${CMS_CONTRACTS}" ]; then
  CONTRACTS_ARGS=(-v "${CMS_CONTRACTS}:/contracts:ro" -e CMS_CONTRACTS_DIR=/contracts)
else
  echo "[test.sh] каталог контрактов CMS не найден (${CMS_CONTRACTS}) — сверка эталонной таблицы не выполнится и покраснеет" >&2
fi

# Версию тулчейна печатаем ПЕРВОЙ строкой — ровно её не хватило в TRM-27.
# Тег `rust:slim` плавающий: в образе может лежать тулчейн старше раннера, и
# тогда новый линт виден только в CI. Печать версии делает расхождение видимым
# сразу; устранить его совсем должен закреплённый тулчейн (см. отчёт TRM-29).
#
# -D warnings: предупреждение = ошибка. Флаги clippy и fmt скопированы из CI
# дословно; расходиться им нельзя — иначе снова «у себя зелено, там красно».
MSYS_NO_PATHCONV=1 docker run --rm \
  -e CARGO_TARGET_DIR=/target \
  -v "${ROOT}/backend:/app" -w /app \
  -v terminal-target:/target \
  -v terminal-registry:/usr/local/cargo/registry \
  -v "${ROOT}/scripts/target-volume-warning.txt:/warning.txt:ro" \
  "${CONTRACTS_ARGS[@]}" \
  rust:slim sh -c '
    set -eu
    # Предупреждение о цене потери кладём В САМ ТОМ, и кладём ЗАНОВО, если его
    # там нет (TRM-39). Иначе защита держалась бы на том, что кто-то однажды
    # положил файл руками: пересоздали том — и предупреждения нет ровно тогда,
    # когда оно нужнее всего. Текст лежит в репозитории, а не в этой строке,
    # потому что править его придётся читателям, а не скрипту.
    [ -f /target/00-НЕ-УДАЛЯТЬ-ЦЕНА-ПОТЕРИ.txt ] || cp /warning.txt /target/00-НЕ-УДАЛЯТЬ-ЦЕНА-ПОТЕРИ.txt
    cargo clippy --version >/dev/null 2>&1 || rustup component add clippy
    cargo fmt --version    >/dev/null 2>&1 || rustup component add rustfmt
    echo "[test.sh] тулчейн: $(rustc --version) | $(cargo clippy --version)"

    echo "[test.sh] --- тесты ---"
    cargo test --workspace "$@"

    echo "[test.sh] --- clippy ---"
    cargo clippy --workspace --all-targets --message-format=short -- -D warnings

    echo "[test.sh] --- формат ---"
    # Шаг БЛОКИРУЮЩИЙ с 21.10 (TRM-37), и ровно так же в `ci.yml`.
    #
    # История нужна, чтобы следующий не развязал их снова. Сперва (TRM-29) он
    # блокировал здесь и не блокировал в CI: команда была скопирована дословно,
    # а её обязательность — нет, и локальный прогон вышел СТРОЖЕ удалённого.
    # Расхождение в любую сторону означает «у себя и там по-разному».
    # Затем он не блокировал в обоих местах — честно, но стиль не выравнивался.
    # Теперь дерево выровнено целиком, и шаг обязателен в обоих местах.
    #
    # Эти две строки — здесь и в `ci.yml` — одно решение, записанное дважды.
    # Меняются ТОЛЬКО ВМЕСТЕ.
    cargo fmt --all -- --check

    echo "[test.sh] Rust: пройдено"
  ' sh "$@"

# ---- Фронт (QA-10) ---------------------------------------------------------
#
# Гоняется ТЕМ ЖЕ `npm test`, что в CI: типы, модульные, браузерные. Своим
# перечнем путей звать нельзя — `run-suites.js` заведён ровно затем, чтобы
# состав наборов жил в одном месте (TRM-26).
#
# Браузер и зависимости — ОБЯЗАТЕЛЬНЫ, и их отсутствие это отказ, а не
# пропуск. Та же мера, что у контрактов CMS выше: непроверенное не должно
# выглядеть пройденным. `findBrowser` отказывает своими словами, поэтому
# здесь проверяется только то, чего он не увидит.
FRONT="${ROOT}/apps/terminal"
echo "[test.sh] --- фронт (npm test) ---"
if ! command -v npm >/dev/null 2>&1; then
  echo "[test.sh] npm не найден — ФРОНТОВЫЕ ПРОВЕРКИ НЕ ВЫПОЛНЕНЫ (это не 'зелено')." >&2
  exit 1
fi
if [ ! -d "${FRONT}/node_modules" ]; then
  echo "[test.sh] нет ${FRONT}/node_modules — фронтовые проверки НЕ ВЫПОЛНЕНЫ." >&2
  echo "[test.sh] Выполните: cd apps/terminal && npm ci" >&2
  exit 1
fi
( cd "${FRONT}" && npm test )

# Итоговая строка печатается ПОСЛЕ ПОСЛЕДНЕЙ проверки — теперь после фронта, а
# не после формата. Раньше она стояла внутри контейнера: добавь кто-нибудь шаг
# после него, и «ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ» печаталось бы ДО этого шага. Ровно так
# 24.10 прогон и считался зелёным по заголовку шага.
#
# Заголовки шагов (`--- формат ---`) печатаются ДО команды и не доказывают
# ничего: отказ после такого заголовка выглядит как успех, особенно если вывод
# читают через grep.
if [ "$#" -gt 0 ]; then
  echo "[test.sh] ⚠ ПРОГОН С ФИЛЬТРОМ ($*) — проверено НЕ ВСЁ, итог ниже относится только к отобранному"
fi
echo "[test.sh] ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ"
